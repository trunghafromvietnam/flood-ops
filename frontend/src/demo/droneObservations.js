// Helper to look up evidence details by filename or observation ID
export function getDroneEvidenceMeta(identifier) {
  if (!identifier) return null
  return (
    DRONE_OBSERVATIONS.find(
      (o) =>
        o.id === identifier ||
        o.filename === identifier ||
        (typeof identifier === 'string' && identifier.includes(o.filename)) ||
        (typeof identifier === 'string' && o.filename.includes(identifier)),
    ) ?? null
  )
}

// Return valid flood images only (for report demo and rapid dispatch)
export function getValidFloodObservations() {
  return DRONE_OBSERVATIONS.filter((o) => o.isValidFlood)
}

// Return invalid observations (for audit and false-positive filter demonstration)
export function getInvalidObservations() {
  return DRONE_OBSERVATIONS.filter((o) => !o.isValidFlood)
}
